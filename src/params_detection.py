"""Extraction of the arguments of a function with constrained decoding."""

from pydantic import BaseModel, InstanceOf
from typing import Any
from llm_sdk import Small_LLM_Model
from .models import FunctionModel, TypeModel
import numpy as np
import json
import regex


class ParamsDetection(BaseModel):
    """Extract the arguments of one function from a prompt.

    The JSON object is built token by token. The program writes the
    structure itself (braces, keys, separators) and the model only
    produces the values. Number values are restricted to tokens that
    keep them valid. Only the ``string`` and ``number`` parameter types
    are supported.

    Attributes:
        llm: The language model used for the generation.
        function: The function whose arguments are extracted.
    """

    llm: InstanceOf[Small_LLM_Model]
    function: FunctionModel

    def model_post_init(self, _: Any) -> None:
        """Build the system message once the fields are validated.

        Called by Pydantic after ``__init__``. It creates the private
        attribute ``_system_message``, the ChatML system turn that
        describes the expected JSON schema.

        Args:
            _: Validation context given by Pydantic. It is not used.
        """
        self._system_message = (
            "<|im_start|>system\n"
            "You extract information from a sentence and "
            "answer ONLY with a JSON object.\n"
            "Schema:\n"
            f" \n{self.generate_default_structure(self.function.parameters)}\n"
            "Use null when information is missing. No extra text.<|im_end|>"
        )

    def generate_default_structure(
        self,
        parameters: dict[str, TypeModel]
    ) -> str:
        """Describe the expected JSON object for the system message.

        Args:
            parameters: Parameter names mapped to their types.

        Returns:
            A schema-like string, for example
            ``{"a": number, "b": number}``.
        """
        result = [
            f'"{key}": {value_type.type}'
            for key, value_type in parameters.items()
        ]
        return f"{{{", ".join(result)}}}"

    def generate(self, prompt: str) -> str:
        """Generate the JSON object with the arguments for a prompt.

        For every parameter, in the order of the function definition,
        the key is appended by the program and the value is generated by
        the model (see ``generate_json_string_value`` and
        ``generate_json_number_value``). The closing brace is added at
        the end.

        Args:
            prompt: The natural-language request of the user.

        Returns:
            The JSON object as text, for example ``{"a": 2.0, "b": 3.0}``.
            It is ``"{}"`` when the function has no parameters.
        """
        user_prompt = (
            "<|im_start|>user\n"
            f"{prompt}<|im_end|>"
        )
        if len(self.function.parameters.items()) == 0:
            return "{}"
        input_ids = self.llm.encode((
            f"{user_prompt}"
            "<|im_start|>assistant\n"
            "<think>\n\n</think>\n\n"
        )).flatten().tolist()
        output_ids: list[int] = []
        with open(self.llm.get_path_to_vocab_file()) as file:
            vocab: dict[str, int] = json.load(file)
        items = 0
        for parameter, type in self.function.parameters.items():
            json_key_tokens_ids = self.llm.encode((
                f"{"{" if items == 0 else ", "}"
                f'"{parameter}": {'"' if type.type == "string" else ""}'
            )).flatten().tolist()
            input_ids = input_ids + json_key_tokens_ids
            output_ids = output_ids + json_key_tokens_ids
            if type.type == "string":
                json_value_tokens_ids = self.generate_json_string_value(
                    input_ids
                )
            elif type.type == "number":
                json_value_tokens_ids = self.generate_json_number_value(
                    input_ids,
                    vocab
                )
            input_ids = input_ids + json_value_tokens_ids
            output_ids = output_ids + json_value_tokens_ids
            items += 1
        output_ids.append(vocab["}"])
        return str(self.llm.decode(output_ids))

    def generate_json_string_value(self, input_ids: list[int]) -> list[int]:
        """Generate the content of a JSON string value.

        The opening quote must already be in ``input_ids``. Tokens are
        chosen greedily until one contains a ``"``. The text before it
        is kept, the closing quote is added and the loop stops. At most
        50 tokens are generated. Escape sequences are not handled.

        Args:
            input_ids: Token ids of the context so far. The list is
                copied and is not modified.

        Returns:
            The token ids of the value, including the closing quote
            when one was found.
        """
        input_ids = list(input_ids)
        token_count = 0
        output_ids: list[int] = []

        while token_count < 50:
            logits = self.llm.get_logits_from_input_ids(input_ids)
            next_token_id = int(np.argmax(logits))
            token = self.llm.decode(next_token_id)
            if '"' in token:
                output_ids = output_ids + self.llm.encode(
                    token[0:token.find('"') + 1]
                ).flatten().tolist()
                break
            output_ids.append(next_token_id)
            input_ids.append(next_token_id)
            token_count += 1
        return output_ids

    def generate_json_number_value(
        self,
        input_ids: list[int],
        vocab: dict[str, int]
    ) -> list[int]:
        """Generate a JSON number value with constrained decoding.

        At each step, the logits of every token that would make the
        number invalid are set to ``-inf`` before choosing the best
        token:

        * the first token can be a digit or ``-``;
        * ``.`` is allowed once, after at least one digit;
        * ``,`` and ``}`` end the number and are allowed only after at
          least one digit.

        At most 50 tokens are generated. If the number has no decimal
        point, ``.0`` is appended.

        Args:
            input_ids: Token ids of the context so far. The list is
                copied and is not modified.
            vocab: Vocabulary of the model, mapping each token text to
                its id.

        Returns:
            The token ids of the number (the terminator is not
            included).
        """
        input_ids = list(input_ids)
        output_ids: list[int] = []
        digit_ids = {
            i for t, i in vocab.items() if regex.fullmatch(r"[0-9]+", t)
        }
        minus, dot = vocab["-"], vocab["."]
        terminators = {vocab[","], vocab["}"]}
        has_digit = has_dot = False

        for _ in range(50):
            allowed = set(digit_ids)
            if not output_ids:
                allowed.add(minus)
            if has_digit and not has_dot:
                allowed.add(dot)
            if has_digit:
                allowed |= terminators

            logits = np.asarray(self.llm.get_logits_from_input_ids(input_ids))
            mask = np.full(len(logits), -np.inf)
            mask[list(allowed)] = 0
            next_id = int(np.argmax(logits + mask))

            if next_id in terminators:
                break
            has_digit |= next_id in digit_ids
            has_dot |= next_id == dot
            output_ids.append(next_id)
            input_ids.append(next_id)
        if not has_dot:
            output_ids.append(vocab["."])
            output_ids.append(vocab["0"])
        return output_ids
